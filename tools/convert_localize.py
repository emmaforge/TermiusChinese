#!/usr/bin/env python3
"""Convert ArcSurge desktop rules/localize.txt into an iOS-safe dictionary.

Usage:
  python3 tools/convert_localize.py /path/to/localize.txt
  # writes TermiusChinese/zh_dict.json and TermiusChinese/zh_dict.h

iOS safety rules (see README):
- Drop comments (#...) and regex rules (/.../): they rewrite JS structure.
- Split each rule on the FIRST '|' (same as desktop lang.py), extract
  quoted strings from both sides positionally, pair them.
- Keep only clean full UI phrases whose translation contains Chinese.
- Drop code fragments, JS objects, trailing-space prefixes.
- Conflicts: keep first, log the rest; then apply OVERRIDES below
  (desktop context-specific first hits that are wrong for iOS).
"""
import json, re, sys
from pathlib import Path

QUOTE = re.compile(r'"((?:[^"\\]|\\.)*)"')
CJK = re.compile(r'[\u4e00-\u9fff]')
OVERRIDES = {'Hosts': '主机', 'Advanced': '高级', 'Team': '团队'}
DROP_KEYS = {'no'}

def clean(s):
    return s.replace('\\"', '"').replace('\\\\', '\\')

def is_clean_en(s):
    if not s or len(s) < 2 or len(s) > 260 or s != s.strip():
        return False
    if any(c in s for c in '{}[]<>;=\n\r\t'):
        return False
    if s.startswith(('http', 'www.', '/', 'case', 'function', 'return')):
        return False
    if re.search(r'\b(var|const|let|function|return|import|export)\b', s):
        return False
    if '__' in s or '=>' in s or '===' in s:
        return False
    return True

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('localize.txt')
    root = Path(__file__).resolve().parent.parent
    pairs, stats = {}, {'lines': 0, 'comment': 0, 'regex': 0, 'mismatch': 0, 'raw': 0}
    for raw in src.read_text(encoding='utf-8').splitlines():
        stats['lines'] += 1
        line = raw.strip()
        if not line or line.startswith('#'):
            stats['comment'] += 1; continue
        if line.startswith('/'):
            stats['regex'] += 1; continue
        if '|' not in line:
            continue
        left, right = line.split('|', 1)
        lq = [clean(m.group(1)) for m in QUOTE.finditer(left)]
        rq = [clean(m.group(1)) for m in QUOTE.finditer(right)]
        if not lq or len(lq) != len(rq):
            stats['mismatch'] += 1; continue
        for en, zh in zip(lq, rq):
            stats['raw'] += 1
            if en == zh or not CJK.search(zh) or not is_clean_en(en):
                continue
            if en in pairs and pairs[en] != zh:
                print(f'CONFLICT {en!r}: keep {pairs[en]!r}, drop {zh!r}')
                continue
            pairs[en] = zh
    pairs.update(OVERRIDES)
    for k in DROP_KEYS:
        pairs.pop(k, None)
    pairs = {k: v for k, v in pairs.items() if '\n' not in k and '\n' not in v}
    out_json = root / 'TermiusChinese' / 'zh_dict.json'
    out_json.write_text(json.dumps(pairs, ensure_ascii=False, indent=2, sort_keys=True) + '\n', encoding='utf-8')
    lines = ['/* Auto-generated by tools/convert_localize.py - do not hand-edit. */',
             '#ifndef TERMIUS_ZH_DICT_H', '#define TERMIUS_ZH_DICT_H', '',
             'typedef struct { const char *en; const char *zh; } TermiusZhPair;',
             'static const TermiusZhPair kTermiusZhPairs[] = {']
    for k, v in sorted(pairs.items()):
        lines.append(f'    {{"{esc(k)}", "{esc(v)}"}},')
    lines += ['};', 'static const unsigned long kTermiusZhPairCount = sizeof(kTermiusZhPairs)/sizeof(kTermiusZhPairs[0]);', '', '#endif']
    (root / 'TermiusChinese' / 'zh_dict.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f"lines={stats['lines']} comment={stats['comment']} regex={stats['regex']} mismatch={stats['mismatch']} raw={stats['raw']} kept={len(pairs)}")
    print(f'wrote {out_json} and zh_dict.h')

if __name__ == '__main__':
    main()
